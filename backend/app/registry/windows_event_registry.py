def _rule_for(event_id):
    """Internal lookup: returns the rule dict or the registry default.

    The detection engine defines Sysmon events under bare numeric keys
    (1, 3, 7, 8, 10, 11, 13) while display registries use 'sysmon_N'. The
    sysmon_N entries for those IDs are aligned to the rules' authoritative
    values at module build time, so '7' and 'sysmon_7' resolve identically no
    matter which API path performs the lookup — while genuinely different
    events (e.g. Terminal Services '21' vs Sysmon 'sysmon_21') stay distinct.
    """
    key = str(event_id or "").strip()
    if not key:
        return dict(DEFAULT_EVENT_RULE)
    rule = WINDOWS_EVENT_RULES.get(key)
    if rule is not None:
        return rule
    sysmon_key = f"sysmon_{key}"
    rule = WINDOWS_EVENT_RULES.get(sysmon_key)
    if rule is not None:
        return rule
    if key.startswith("sysmon_"):
        rule = WINDOWS_EVENT_RULES.get(key[7:])
        if rule is not None:
            return rule
    return dict(DEFAULT_EVENT_RULE)


def get_event_rule(event_id):
    """Authoritative Event ID rule: {name, cat, detection, severity, mitre,
    description, recommendation}. Always returns a rule (registry default for
    unmapped IDs) — never None, so every consumer sees identical values."""
    rule = _rule_for(event_id)
    rule = dict(rule)
    if rule.get("name") == "Windows Event ID {id}":
        rule["name"] = rule["name"].format(id=str(event_id or "").replace("sysmon_", ""))
    return rule


def get_process_rule(process_name):
    """Authoritative process rule (basename lookup), or None."""
    if not process_name:
        return None
    process = process_name.lower().split("\\")[-1]
    rule = PROCESS_RULES.get(process)
    if rule is None:
        # allow 'powershell.exe' / 'POWERSHELL.EXE' style mismatches
        rule = PROCESS_RULES.get(process_name)
    return rule


def supported_event_ids():
    return sorted({str(k).replace("sysmon_", "") for k in WINDOWS_EVENT_RULES})


def supported_processes():
    return sorted(PROCESS_RULES.keys())


def resolve_mitre(mitre_id):
    """Resolve a MITRE id to {technique, tactic} via the glossary."""
    if not mitre_id or mitre_id in ("N/A", "Unknown"):
        return {"id": mitre_id or "N/A", "technique": "Unknown", "tactic": "Unknown"}
    entry = MITRE_MATRIX_GLOSSARY.get(mitre_id)
    if entry:
        return {"id": mitre_id, "technique": entry.get("technique", mitre_id),
                "tactic": entry.get("tactic", "Unknown")}
    return {"id": mitre_id, "technique": mitre_id, "tactic": "Unknown"}


