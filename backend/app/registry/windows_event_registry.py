SEVERITY_COUNT_KEYS = ["Critical", "High", "Medium", "Low", "Informational"]


def _normalize_severity_value(raw):
    """Map any stored severity representation to a canonical display level.

    Empty / Unknown / None map to Informational so displayed severities stay
    consistent with SQL-side counting and the dashboard analytics. This is the
    registry's explicit justification for the Informational default above.
    """
    s = str(raw or "").strip()
    if not s or s.lower() in ("unknown", "none", "null", "info", "informational"):
        return "Informational"
    cap = s.capitalize()
    return cap if cap in SEVERITY_COUNT_KEYS else "Informational"


# Enterprise metadata suffixes some event sources append to a process token,
# e.g. 'app.exe, version: 1.2.3, time stamp: 0x6a3570a5' (Task 27). The Process
# field must contain the actual process name, so everything from the first
# ', version:' / ', time stamp:' / ', timestamp:' marker is stripped.
_PROCESS_SUFFIX_RE = re.compile(r",\s*(version|time\s*stamp|timestamp)\s*:")


def _clean_process_token(value):
    """Strip trailing enterprise metadata from one process token."""
    if not value:
        return value
    cleaned = _PROCESS_SUFFIX_RE.split(value.strip(), maxsplit=1)[0]
    return cleaned.strip().rstrip(",").strip()


def sanitize_process_name(image_path, fallback_name):
    """Win32 executable-image extraction: basename of the image path, with
    explicit enterprise tags for missing markers (never 'N/A' leak) and any
    ', version:' / ', time stamp:' suffixes stripped (Task 27).

    When the event genuinely contains no process information (no image, no
    process name), the explicit PROCESS_NOT_AVAILABLE sentinel is returned —
    never a fabricated placeholder like '[System Process]'.
    """
    img_clean = image_path.strip() if image_path else ""
    fallback_clean = _clean_process_token(fallback_name)

    def _empty(value):
        return not value or str(value).strip().lower() in {"-", "none", "null", "n/a", "(null)"}

    if _empty(img_clean):
        if _empty(fallback_clean):
            return PROCESS_NOT_AVAILABLE
        return fallback_clean

    base_name = _clean_process_token(img_clean.replace("\\", "/").split("/")[-1])
    if _empty(base_name):
        return fallback_clean if not _empty(fallback_clean) else PROCESS_NOT_AVAILABLE
    return base_name


def normalize_process_id(raw):
    """Canonical PID display value: the real PID when present, else the
    explicit PID_NOT_AVAILABLE sentinel — never '-' or ''."""
    value = str(raw or "").strip()
    if not value or value.lower() in {"-", "none", "null", "n/a", "(null)"} or value == "0":
        return PID_NOT_AVAILABLE
    return value


def build_mitre_block(mitre_id, detection_name="", severity=""):
    """Canonical MITRE ATT&CK result for one event.

    Returns the enriched block every read path consumes:
      If a single mitre_id is provided, returns a single block:
      {id, name, technique, tactic, confidence, reason}
      
      If a list of mitre_ids is provided, returns a list of blocks:
      [
          {id, name, technique, tactic, confidence, reason},
          ...
      ]

    - id: technique/sub-technique id (e.g. 'T1059.001') or MITRE_UNMAPPED when
      the event evidence supports no mapping — a technique is NEVER assigned
      merely because an Event ID resembles one.
    - name: short technique name (sub-technique when applicable), derived from
      the glossary ('Command and Scripting Interpreter: PowerShell' ->
      'PowerShell').
    - confidence: how strongly the detection evidence supports the mapping
      (severity-based, 0.0 when unmapped).
    - reason: the actual detection rule that produced the mapping.
    """
    # Handle multiple MITRE ids
    if isinstance(mitre_id, list):
        results = []
        for mid in mitre_id:
            block = build_mitre_block(mid, detection_name, severity)
            results.append(block)
        return results
    
    # Handle single MITRE id (original logic)
    raw_id = str(mitre_id or "").strip()
    if not raw_id or raw_id.lower() in {"n/a", "unknown", "none", "null", "-"}:
        return {
            "id": MITRE_UNMAPPED,
            "name": MITRE_UNMAPPED,
            "technique": "No applicable MITRE ATT&CK technique",
            "tactic": "Unknown",
            "confidence": 0.0,
            "reason": "No detection evidence maps this event to a MITRE ATT&CK technique.",
        }

    resolved = resolve_mitre(raw_id)
    technique = resolved.get("technique") or raw_id
    tactic = resolved.get("tactic") or "Unknown"

    name = technique
    if ": " in technique:
        name = technique.rsplit(": ", 1)[-1].strip()

    severity_key = str(severity or "").strip().capitalize()
    confidence = {
        "Critical": 0.95, "High": 0.9, "Medium": 0.8,
        "Low": 0.7, "Informational": 0.5,
    }.get(severity_key, 0.5)

    reason = str(detection_name or "").strip()
    if not reason:
        reason = f"Mapped by Event ID {raw_id}"

    return {
        "id": raw_id,
        "name": name,
        "technique": technique,
        "tactic": tactic,
        "confidence": confidence,
        "reason": reason,
    }


def normalize_event_description(raw):
    """Canonical event description: real description when present, else the
    explicit 'Unknown Windows Event' label for unmapped events."""
    value = str(raw or "").strip()
    if not value or value.lower() in _LEGACY_DEFAULT_DESCRIPTIONS:
        return DEFAULT_EVENT_RULE["description"]
    return value


def is_sysmon_event(event_block):
    """True ONLY when the event actually came from the Sysmon provider.

    Sysmon is determined from the real channel / source / provider fields
    (e.g. channel "Microsoft-Windows-Sysmon/Operational", source "Sysmon"),
    NEVER from the numeric Event ID alone — a Windows event that happens to
    share a number with a Sysmon event (e.g. Security 1 vs Sysmon 1) must not
    be classified as Sysmon. This is the single shared classifier used by
    Alerts and Timeline so the same event classifies identically end-to-end.
    """
    block = event_block or {}
    haystack = " ".join([
        str(block.get("channel", "") or ""),
        str(block.get("source", "") or ""),
        str(block.get("provider", "") or ""),
    ]).lower()
    return "sysmon" in haystack


def resolve_event_lookup_id(event_block):
    """Registry lookup key ('sysmon_N' or 'N') for one event block.

    The single shared classification for every read path (Alerts, Timeline,
    Dashboard): Sysmon events resolve to their sysmon_<N> registry entry,
    everything else to the bare numeric id. Classification never depends on the
    numeric Event ID — only on the actual channel/source/provider.
    """
    raw_id = str((event_block or {}).get("event_id", "") or "")
    if is_sysmon_event(event_block):
        return f"sysmon_{raw_id}"
    return raw_id


def enrich_log_payload(event_id, current_severity="", command_line=""):
    """Resolve detection / severity / MITRE for one Event ID.

    Uses ONLY the authoritative registry. A non-default stored severity (e.g.
    from a process rule like powershell.exe -> High) is preserved; otherwise the
    Event ID's registry severity applies, so every API path shows the same
    severity for the same event.
    """
    id_str = str(event_id or "")
    cmd_lower = command_line.lower() if command_line else ""

    rule = get_event_rule(id_str)

    resolved_severity = rule["severity"]
    mitre_id = rule["mitre"]["id"]

    # Command-line intelligence for process-creation events (kept behavior).
    if id_str in ["4688", "1", "4104"]:
        if "mimikatz" in cmd_lower or "lsass" in cmd_lower or "dump" in cmd_lower:
            mitre_id = "T1003.001"
            resolved_severity = "Critical"
        elif "powershell" in cmd_lower and ("-enc" in cmd_lower or "bypass" in cmd_lower):
            resolved_severity = "High"
            mitre_id = "T1059.001"

    if current_severity and str(current_severity).strip().lower() not in ["info", "informational", "", "none", "unknown"]:
        resolved_severity = current_severity

    mitre_details = resolve_mitre(mitre_id)

    # Full enriched MITRE block (id/name/technique/tactic/confidence/reason,
    # "Unmapped" for events with no applicable mapping) — the single shape
    # every consumer renders.
    mitre_block = build_mitre_block(
        mitre_id, rule["detection"], resolved_severity
    )

    return {
        "detection": rule["detection"],
        "severity": resolved_severity,
        "mitre_id": mitre_id,
        "technique": mitre_details["technique"],
        "tactic": mitre_details["tactic"],
        "mitre": mitre_block,
    }